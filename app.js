/* ---------- API wrapper (used when USE_DEMO = false) ---------- */
async function api(path, { method = 'GET', body, form } = {}) {
  if (CONFIG.USE_DEMO) return null;
  const opt = { method, credentials: 'include', headers: {} };
  if (form) opt.body = form;
  else if (body) { opt.headers['Content-Type'] = 'application/json'; opt.body = JSON.stringify(body); }
  const r = await fetch(CONFIG.API_BASE + path, opt);
  const j = await r.json().catch(() => ({}));
  if (!r.ok) throw new Error(j.message || 'Request failed');
  return j;
}

/* ---------- Demo-mode accounts ----------
   Demo mode has no server, so these functions play the part of /auth/login and /auth/register and enforce the SAME
   rules as api/index.php (name required, valid e-mail, password >= 8, phone 6-20 chars, unique e-mail, suspended users
   blocked). The password check uses a small salted hash. It is NOT security (everything is in the visitor's own
   browser); it only stops the demo from accepting any password. */
const demoHash = s => { let a = 0x811c9dc5, b = 0x1b873593; for (const ch of 'pb$' + s) { a = Math.imul(a ^ ch.charCodeAt(0), 16777619) >>> 0; b = Math.imul(b + ch.charCodeAt(0), 2246822519) >>> 0; } return a.toString(16) + b.toString(16); };
const DEMO_PW = { 'admin@petbio.com': 'admin123' };           // everyone else seeded in DEMO.users uses "demo123"
const demoAuth = {
  users: () => Store.get('a_users', DEMO.users),
  pwHash(u) { const own = Store.get('a_pw', {})[u.email.toLowerCase()]; return own || demoHash(DEMO_PW[u.email.toLowerCase()] || 'demo123'); },
  login(email, password) {
    const u = this.users().find(x => x.email && x.email.toLowerCase() === String(email || '').trim().toLowerCase());
    if (!u || this.pwHash(u) !== demoHash(String(password || ''))) throw new Error('Wrong email or password.');
    if (u.is_active === 0) throw new Error('This account is suspended. Please contact the admin.');
    return { user_id: u.user_id, name: u.name, email: u.email, phone: u.phone, address: u.address, role: u.role };
  },
  register(f) {
    const name = String(f.name || '').trim(), email = String(f.email || '').trim().toLowerCase(), phone = String(f.phone || '').trim();
    if (!name) throw new Error('Name is required.');
    if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email)) throw new Error('Enter a valid email address.');
    if (String(f.password || '').length < 8) throw new Error('Password must be at least 8 characters.');
    if (phone && !/^[0-9+\-\s]{6,20}$/.test(phone)) throw new Error('Enter a valid phone number.');
    const users = this.users();
    if (users.some(x => x.email && x.email.toLowerCase() === email)) throw new Error('That email is already registered.');
    const u = { user_id: Math.max(0, ...users.map(x => x.user_id)) + 1, name, email, phone, address: String(f.address || '').trim(), role: 'user', is_active: 1, created_at: todayISO() };
    Store.set('a_users', [...users, u]); Store.set('a_pw', { ...Store.get('a_pw', {}), [email]: demoHash(String(f.password)) });
    return { user_id: u.user_id, name, email, phone, address: u.address, role: 'user' };
  }
};

