/* Multi-photo uploader with previews. Returns { files() } */
function setupDropzone(zone, input, preview, { multiple = true, max = 6 } = {}) {
  let files = [];
  const render = () => {
    preview.innerHTML = '';
    files.forEach((f, i) => {
      const d = document.createElement('div'); d.className = 'prev';
      d.innerHTML = `<img src="${URL.createObjectURL(f)}" alt=""><button type="button" title="Remove">✕</button>${i === 0 && multiple ? '<span class="pri">Main</span>' : ''}`;
      d.querySelector('button').onclick = e => { e.stopPropagation(); files.splice(i, 1); render(); zone.dispatchEvent(new Event('change')); };
      preview.appendChild(d);
    });
  };
  const add = list => {
    [...list].filter(f => f.type.startsWith('image/')).forEach(f => {
      if (!multiple) files = [f]; else if (files.length < max) files.push(f); else toast('Maximum ' + max + ' photos allowed', 'err');
    });
    render(); zone.dispatchEvent(new Event('change'));
  };
  zone.onclick = () => input.click();
  input.onchange = () => { add(input.files); input.value = ''; };
  zone.ondragover = e => { e.preventDefault(); zone.classList.add('drag'); };
  zone.ondragleave = () => zone.classList.remove('drag');
  zone.ondrop = e => { e.preventDefault(); zone.classList.remove('drag'); add(e.dataTransfer.files); };
  return { files: () => files, add, clear: () => { files = []; render(); zone.dispatchEvent(new Event('change')); } };
}

